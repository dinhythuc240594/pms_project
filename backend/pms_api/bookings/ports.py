"""Persistence operations used by reservation application services."""

from typing import Any, Protocol


class ReservationRepository(Protocol):
    def find_reservation(self, tenant_id, reservation_id, *, locked=False) -> Any: ...
    def rows_for(self, model, tenant_id, reservation_id=None) -> list: ...
    def totals(self, row) -> tuple: ...
    def load_booking_data(self, tenant_id, reservation_id=None) -> dict: ...
